"""Builds guna_lookup.sql: all 108 x 108 boy-pada x girl-pada combinations (11,664 rows).

    python -m tools.gen_guna_lookup > guna_lookup.sql
"""
from __future__ import annotations

import json
import sys

from likha_kundli.milan import MoonPoint, ashtakoota
from likha_kundli.rules import RULES_VERSION


def rows():
    for bn in range(27):
        for bp in range(1, 5):
            for gn in range(27):
                for gp in range(1, 5):
                    m = ashtakoota(MoonPoint(bn, bp), MoonPoint(gn, gp))
                    yield bn, bp, gn, gp, m


def build_sql(batch: int = 500) -> str:
    out = [f"-- guna_lookup generated by likha-kundli, rules {RULES_VERSION}",
           "begin;", "truncate public.guna_lookup;"]
    buf = []
    for bn, bp, gn, gp, m in rows():
        k = m.kootas
        doshas = json.dumps(m.doshas, separators=(",", ":")).replace("'", "''")
        buf.append(f"({bn},{bp},{gn},{gp},{k['varna']},{k['vashya']},{k['tara']},{k['yoni']},"
                   f"{k['graha_maitri']},{k['gana']},{k['bhakoot']},{k['nadi']},{m.total},{m.adjusted_total},"
                   f"'{doshas}','{RULES_VERSION}')")
        if len(buf) == batch:
            out.append(_insert(buf))
            buf = []
    if buf:
        out.append(_insert(buf))
    out.append("commit;")
    return "\n".join(out) + "\n"


def _insert(vals):
    return ("insert into public.guna_lookup (boy_nakshatra,boy_pada,girl_nakshatra,girl_pada,varna,vashya,tara,yoni,"
            "graha_maitri,gana,bhakoot,nadi,total,adjusted_total,doshas,rules_version) values\n" + ",\n".join(vals) + ";")


if __name__ == "__main__":
    sys.stdout.write(build_sql())
